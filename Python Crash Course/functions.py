def sum(a,b,c,d=0,e=0):
    return (a -(b-(c-(d-e))))

print("The sum of 3 values is ", sum(12,12,2))
print("The sum of 4 values is ", sum(12,12,2,10))
print("The sum of 5 values is ", sum(12,12,2,22,11))

def force(m,a):
    return (m*a)
print("The force applied is : ",force(2,10))

def electrical_power(V,I):
    return (V*I)
print("The Electrical power is : ", electrical_power(10,10))

def power(I,R):
    return I*R
print("The power from current and resistance is : ", power(10,3))

